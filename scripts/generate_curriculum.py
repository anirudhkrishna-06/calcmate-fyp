"""Generate the mobile curriculum from the authoritative project CSV files."""
import csv
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from src.classroom_contracts import curriculum_version


def main():
    with (ROOT / "data/concepts.csv").open(encoding="utf-8-sig") as source:
        concepts = [c for c in csv.DictReader(source) if c["is_active"].lower() != "false"]
    ids = {c["id"] for c in concepts}
    with (ROOT / "data/prerequisite_edges.csv").open(encoding="utf-8-sig") as source:
        edges = [(e["target_concept_id"], e["source_concept_id"]) for e in csv.DictReader(source) if e["target_concept_id"] in ids and e["source_concept_id"] in ids]
    seed = [[c["id"], c["concept"], int(c["grade"]), next((b for a, b in edges if a == c["id"]), None)] for c in concepts]
    metadata = {c["id"]: {"learning_objective": c["learning_objective"], "coverage_status": c["coverage_status"], "subject_area": c["subject"]} for c in concepts}
    text = "// Generated by scripts/generate_curriculum.py; edit the canonical CSV files.\n"
    text += "export const curriculumVersion=" + json.dumps(curriculum_version()) + ";\n"
    text += "export const canonicalConceptSeed=" + json.dumps(seed, ensure_ascii=False, indent=2) + " as const;\n"
    text += "export const canonicalPrerequisiteSeed=" + json.dumps(edges, indent=2) + " as const;\n"
    text += "export const canonicalConceptMetadata=" + json.dumps(metadata, ensure_ascii=False, indent=2) + " as const;\n"
    (ROOT / "frontend/src/data/curriculum.ts").write_text(text, encoding="utf-8")
    print(f"Generated {len(seed)} concepts and {len(edges)} edges, Grades 1-5.")


if __name__ == "__main__":
    main()
